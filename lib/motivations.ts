function pickDaily(list: string[]): string {
  const dayOfYear = Math.floor(
    (Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 86400000
  )
  return list[dayOfYear % list.length]
}

export function getDailyMotivation(trackingType?: 'pregnancy' | 'baby' | null): string {
  return pickDaily(trackingType === 'pregnancy' ? pregnancyMotivations : babyMotivations)
}

export function getRandomMotivation(trackingType?: 'pregnancy' | 'baby' | null): string {
  const list = trackingType === 'pregnancy' ? pregnancyMotivations : babyMotivations
  return list[Math.floor(Math.random() * list.length)]
}
